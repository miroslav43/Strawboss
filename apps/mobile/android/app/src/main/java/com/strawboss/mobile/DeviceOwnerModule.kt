  /**
   * Gather a diagnostic snapshot of the device: battery, charging, device-owner
   * status, Tailscale install, installed package count, and granted runtime
   * permissions. Each piece is independently guarded so one failure doesn't kill
   * the whole call.
   */
  @ReactMethod
  fun getDeviceState(promise: Promise) {
    try {
      val map = Arguments.createMap()

      // Battery percentage
      try {
        val bm = ctx.getSystemService(Context.BATTERY_SERVICE) as BatteryManager
        val pct = bm.getIntProperty(BatteryManager.BATTERY_PROPERTY_CAPACITY)
        if (pct >= 0) map.putInt("batteryPct", pct) else map.putNull("batteryPct")
      } catch (t: Throwable) { map.putNull("batteryPct") }

      // Charging status
      try {
        val bm = ctx.getSystemService(Context.BATTERY_SERVICE) as BatteryManager
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) {
          map.putBoolean("isCharging", bm.isCharging)
        } else {
          val filter = IntentFilter(Intent.ACTION_BATTERY_CHANGED)
          val intent = ctx.registerReceiver(null, filter)
          val status = intent?.getIntExtra(BatteryManager.EXTRA_STATUS, -1) ?: -1
          map.putBoolean("isCharging",
            status == BatteryManager.BATTERY_STATUS_CHARGING ||
            status == BatteryManager.BATTERY_STATUS_FULL)
        }
      } catch (t: Throwable) { map.putNull("isCharging") }

      // Device owner
      try {
        map.putBoolean("isDeviceOwner", DeviceOwnerPolicies.isDeviceOwner(ctx))
      } catch (t: Throwable) { map.putBoolean("isDeviceOwner", false) }

      // Tailscale installed
      try {
        if (Build.VERSION.SDK_INT >= 33) {
          ctx.packageManager.getPackageInfo("com.tailscale.ipn",
            android.content.pm.PackageManager.PackageInfoFlags.of(0L))
        } else {
          @Suppress("DEPRECATION")
          ctx.packageManager.getPackageInfo("com.tailscale.ipn", 0)
        }
        map.putBoolean("tailscaleInstalled", true)
      } catch (e: android.content.pm.PackageManager.NameNotFoundException) {
        map.putBoolean("tailscaleInstalled", false)
      } catch (t: Throwable) { map.putBoolean("tailscaleInstalled", false) }

      // Installed package count
      try {
        val count = ctx.packageManager.getInstalledApplications(0).size
        map.putInt("installedPackageCount", count)
      } catch (t: Throwable) { map.putNull("installedPackageCount") }

      // App version
      try {
        map.putString("appVersion", Build.VERSION.RELEASE)
      } catch (t: Throwable) { map.putNull("appVersion") }

      // Granted runtime permissions for this app
      try {
        val pm = ctx.packageManager
        val pkgInfo: PackageInfo = if (Build.VERSION.SDK_INT >= 33) {
          pm.getPackageInfo(ctx.packageName,
            android.content.pm.PackageManager.PackageInfoFlags.of(
              android.content.pm.PackageManager.GET_PERMISSIONS.toLong()))
        } else {
          @Suppress("DEPRECATION")
          pm.getPackageInfo(ctx.packageName,
            android.content.pm.PackageManager.GET_PERMISSIONS)
        }
        val grantedArr = Arguments.createArray()
        val perms = pkgInfo.requestedPermissions ?: emptyArray()
        val flags = pkgInfo.requestedPermissionsFlags ?: IntArray(0)
        for (i in perms.indices) {
          if (i < flags.size &&
              (flags[i] and PackageInfo.REQUESTED_PERMISSION_GRANTED) != 0) {
            grantedArr.pushString(perms[i])
          }
        }
        map.putArray("grantedPermissions", grantedArr)
      } catch (t: Throwable) {
        map.putArray("grantedPermissions", Arguments.createArray())
      }

      promise.resolve(map)
    } catch (t: Throwable) {
      promise.reject("DO_DEVICE_STATE", t.message ?: t.toString())
    }
  }

  /**
   * Check whether a package is installed on this device.
   * Returns true if [packageName] is installed, false if not (NameNotFoundException).
   * Safe to call on any Android API level; never throws to JS.
   * Uses PackageInfoFlags on API 33+ to avoid the deprecated int-flag overload.
   */
  @ReactMethod
  fun isPackageInstalled(packageName: String, promise: Promise) {
    try {
      if (Build.VERSION.SDK_INT >= 33) {
        ctx.packageManager.getPackageInfo(packageName, android.content.pm.PackageManager.PackageInfoFlags.of(0))
      } else {
        @Suppress("DEPRECATION")
        ctx.packageManager.getPackageInfo(packageName, 0)
      }
      promise.resolve(true)
    } catch (e: android.content.pm.PackageManager.NameNotFoundException) {
      promise.resolve(false)
    } catch (t: Throwable) {
      promise.reject("DO_PKG_CHECK", t.message ?: t.toString())
    }
  }

  /**
   * Silently install an APK via the Device Owner PackageInstaller API.
   *
   * Steps:
   *   1. SHA-256 verify: compute digest of the file at [path]; reject with
   *      SHA_MISMATCH if it does not equal [expectedSha256] (case-insensitive hex).
   *      Never proceed with an unverified APK.
   *   2. Open a PackageInstaller.Session with MODE_FULL_INSTALL +
   *      setAppPackageName(packageName), stream the APK, fsync, close.
   *   3. Commit via a PendingIntent targeting InstallResultReceiver; as Device
   *      Owner this silently installs with no user prompt.
   *   4. Resolve true after commit is dispatched. The process is typically KILLED
   *      during self-update — JS must persist intent BEFORE calling this.
   *
   * [packageName] must be the target package (e.g. "com.strawboss.mobile" for a
   * self-update or "com.tailscale.ipn" for Tailscale). Passing the wrong name
   * here causes a package-name conflict during install.
   */
  @ReactMethod
  fun installApkSilent(path: String, expectedSha256: String, packageName: String, promise: Promise) {
    try {
      // Step 1: SHA-256 verify
      val file = File(path)
      if (!file.exists()) {
        promise.reject("FILE_NOT_FOUND", "APK file not found: $path")
        return
      }
      val digest = MessageDigest.getInstance("SHA-256")
      FileInputStream(file).use { fis ->
        val buf = ByteArray(8192)
        var n: Int
        while (fis.read(buf).also { n = it } != -1) {
          digest.update(buf, 0, n)
        }
      }
      val actualHex = digest.digest().joinToString("") { "%02x".format(it) }
      if (!actualHex.equals(expectedSha256.trim(), ignoreCase = true)) {
        promise.reject("SHA_MISMATCH", "APK SHA-256 mismatch: expected $expectedSha256, got $actualHex")
        return
      }

      // Step 2: Open a PackageInstaller session
      val installer = ctx.packageManager.packageInstaller
      val params = PackageInstaller.SessionParams(PackageInstaller.SessionParams.MODE_FULL_INSTALL)
      params.setAppPackageName(packageName)
      val sessionId = installer.createSession(params)
      val session = installer.openSession(sessionId)

      try {
        session.openWrite("base.apk", 0, file.length()).use { out ->
          FileInputStream(file).use { fis ->
            val buf = ByteArray(65536)
            var n: Int
            while (fis.read(buf).also { n = it } != -1) {
              out.write(buf, 0, n)
            }
          }
          session.fsync(out)
        }

        // Step 3: Commit
        val resultIntent = Intent(ctx, InstallResultReceiver::class.java)
        var piFlags = PendingIntent.FLAG_UPDATE_CURRENT
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
          piFlags = piFlags or PendingIntent.FLAG_MUTABLE
        }
        val pi = PendingIntent.getBroadcast(ctx, sessionId, resultIntent, piFlags)
        session.commit(pi.intentSender)
        Log.i("StrawbossOTA", "PackageInstaller session committed (id=$sessionId)")
      } catch (t: Throwable) {
        try { session.abandon() } catch (t2: Throwable) { /* ignore */ }
        throw t
      } finally {
        try { session.close() } catch (t: Throwable) { /* ignore */ }
      }

      // Step 4: resolve true — the process will likely be killed mid-install
      promise.resolve(true)
    } catch (t: Throwable) {
      promise.reject("DO_INSTALL", t.message ?: t.toString())
    }
  }
}

/**
 * GENERATED by plugins/withDeviceOwner.js — do not edit by hand.
 * Receives PackageInstaller session status broadcasts for silent OTA installs.
 * This is best-effort logging only — the JS promise is already resolved before
 * commit() fires the broadcast, and the process is typically killed during
 * a self-update before this receiver runs.
 */
class InstallResultReceiver : BroadcastReceiver() {
  override fun onReceive(context: Context, intent: Intent) {
    val status = intent.getIntExtra(PackageInstaller.EXTRA_STATUS, PackageInstaller.STATUS_FAILURE)
    val msg = intent.getStringExtra(PackageInstaller.EXTRA_STATUS_MESSAGE) ?: ""
    when (status) {
      PackageInstaller.STATUS_SUCCESS ->
        Log.i("StrawbossOTA", "Silent install succeeded")
      PackageInstaller.STATUS_PENDING_USER_ACTION -> {
        // Device owner should never reach this — log as a warning
        Log.w("StrawbossOTA", "Install requires user action (not device owner?): $msg")
      }
      else ->
        Log.w("StrawbossOTA", "Silent install failed: status=$status msg=$msg")
    }
  }
}
