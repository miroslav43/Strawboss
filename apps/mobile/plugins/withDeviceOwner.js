function withManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const manifest = cfg.modResults.manifest;

    // Ensure <uses-permission android:name="android.permission.REQUEST_INSTALL_PACKAGES"/>
    manifest['uses-permission'] = manifest['uses-permission'] || [];
    const installPerm = 'android.permission.REQUEST_INSTALL_PACKAGES';
    if (!manifest['uses-permission'].some((p) => p.$?.['android:name'] === installPerm)) {
      manifest['uses-permission'].push({ $: { 'android:name': installPerm } });
    }

    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);

    app.receiver = app.receiver || [];
    if (!app.receiver.some((r) => r.$?.['android:name'] === '.StrawbossDeviceAdminReceiver')) {
      app.receiver.push({
        $: {
          'android:name': '.StrawbossDeviceAdminReceiver',
          'android:permission': 'android.permission.BIND_DEVICE_ADMIN',
          'android:exported': 'true',
        },
        'meta-data': [
          {
            $: {
              'android:name': 'android.app.device_admin',
              'android:resource': '@xml/device_admin',
            },
          },
        ],
        'intent-filter': [
          {
            action: [
              { $: { 'android:name': 'android.app.action.DEVICE_ADMIN_ENABLED' } },
              { $: { 'android:name': 'android.app.action.PROFILE_PROVISIONING_COMPLETE' } },
            ],
          },
        ],
      });
    }

    // Keep-alive presence foreground service (specialUse: honest "we hold a
    // background connection alive" — no timeout, unlike dataSync). Started only
    // for device-owner roles without an assigned machine.
    app.service = app.service || [];
    if (!app.service.some((s) => s.$?.['android:name'] === '.PresenceService')) {
      app.service.push({
        $: {
          'android:name': '.PresenceService',
          'android:exported': 'false',
          'android:foregroundServiceType': 'specialUse',
        },
        property: [
          {
            $: {
              'android:name': 'android.app.PROPERTY_SPECIAL_USE_FGS_SUBTYPE',
              'android:value': 'presence_heartbeat',
            },
          },
        ],
      });
    }

    // OTA install result receiver (exported=false — only receives broadcasts from
    // the app's own PackageInstaller sessions via the explicit PendingIntent).
    app.receiver = app.receiver || [];
    if (!app.receiver.some((r) => r.$?.['android:name'] === '.InstallResultReceiver')) {
      app.receiver.push({
        $: {
          'android:name': '.InstallResultReceiver',
          'android:exported': 'false',
        },
      });
    }

    app.activity = app.activity || [];
    if (!app.activity.some((a) => a.$?.['android:name'] === '.GeofenceAlertActivity')) {
      app.activity.push({
        $: {
          'android:name': '.GeofenceAlertActivity',
          'android:exported': 'false',
          'android:theme': '@android:style/Theme.Translucent.NoTitleBar',
          'android:excludeFromRecents': 'true',
          'android:noHistory': 'true',
          'android:launchMode': 'singleTop',
          'android:taskAffinity': '',
          'android:showWhenLocked': 'true',
          'android:turnScreenOn': 'true',
        },
      });
    }

    return cfg;
  });
}

