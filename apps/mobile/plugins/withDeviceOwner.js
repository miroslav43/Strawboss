function withKotlinSources(config) {
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const root = cfg.modRequest.platformProjectRoot;
      const javaDir = path.join(root, 'app', 'src', 'main', 'java', ...PACKAGE.split('.'));
      fs.mkdirSync(javaDir, { recursive: true });
      fs.writeFileSync(
        path.join(javaDir, 'StrawbossDeviceAdminReceiver.kt'),
        DEVICE_ADMIN_RECEIVER_KT,
      );
      fs.writeFileSync(path.join(javaDir, 'DeviceOwnerPolicies.kt'), DEVICE_OWNER_POLICIES_KT);
      fs.writeFileSync(path.join(javaDir, 'GeofenceAlertActivity.kt'), GEOFENCE_ALERT_ACTIVITY_KT);
      fs.writeFileSync(path.join(javaDir, 'DeviceOwnerModule.kt'), DEVICE_OWNER_MODULE_KT);
      fs.writeFileSync(path.join(javaDir, 'DeviceOwnerPackage.kt'), DEVICE_OWNER_PACKAGE_KT);
      fs.writeFileSync(path.join(javaDir, 'PresenceService.kt'), PRESENCE_SERVICE_KT);

      const xmlDir = path.join(root, 'app', 'src', 'main', 'res', 'xml');
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, 'device_admin.xml'), DEVICE_ADMIN_XML);

      patchMainApplication(javaDir);
      return cfg;
    },
  ]);
}

/** Register DeviceOwnerPackage in MainApplication.getPackages() (idempotent). */
function patchMainApplication(javaDir) {
  const mainAppPath = path.join(javaDir, 'MainApplication.kt');
  if (!fs.existsSync(mainAppPath)) return;
  let src = fs.readFileSync(mainAppPath, 'utf8');
  if (src.includes('DeviceOwnerPackage()')) return; // already patched

  const anchor = 'PackageList(this).packages.apply {';
  const idx = src.indexOf(anchor);
  if (idx === -1) return;
  const insertAt = idx + anchor.length;
  src = src.slice(0, insertAt) + '\n              add(DeviceOwnerPackage())' + src.slice(insertAt);
  fs.writeFileSync(mainAppPath, src);
}

