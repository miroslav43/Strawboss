/**
 * Expo config plugin: Device Owner (fully-managed device) + over-everything alerts.
 *
 * Turns StrawBoss into its own Device Policy Controller (DPC) so that, on the
 * ~30 dedicated operator phones provisioned as Device Owner (QR / `adb dpm
 * set-device-owner`), the app can:
 *   1. AUTO-GRANT all its own runtime permissions with zero taps — including
 *      ACCESS_BACKGROUND_LOCATION ("Allow all the time"), which only a *device
 *      owner* (not a profile owner) is allowed to grant on Android 12+.
 *   2. Make itself impossible to force-stop / clear / uninstall
 *      (setUserControlDisabledPackages + setUninstallBlocked) and survive reboots
 *      (DISALLOW_SAFE_BOOT + the existing BootReceiver).
 *   3. Launch its alert UI OVER ANY OTHER APP and over the lock screen, because a
 *      device owner is exempt from background-activity-start restrictions — so
 *      `GeofenceAlertActivity` can be started directly from the background GPS
 *      task (no SYSTEM_ALERT_WINDOW, which stays blocked).
 *
 * The phone remains a NORMAL usable phone: we never call setLockTaskPackages and
 * never enter kiosk/lock-task. Only the StrawBoss app itself is locked down.
 *
 * Non-device-owner installs fall back to a native full-screen-intent notification
 * (USE_FULL_SCREEN_INTENT) that wakes the screen over the lock screen — same
 * `GeofenceAlertActivity`, no third-party notification library.
 *
 * Mirrors plugins/withAlwaysOnTracking.js exactly (withAndroidManifest +
 * withDangerousMod writing Kotlin into android/app/src/main/java/...). The
 * android/ dir is regenerated by `expo prebuild`, so all native edits live here.
 *
 * IMPORTANT for provisioning: do NOT add
 * `android.app.extra.PROVISIONING_SENSORS_PERMISSION_GRANT_OPT_OUT` to the QR
 * payload — its presence revokes the device owner's ability to grant sensor
 * permissions (background location). See tools/provisioning/generate-qr.mjs.
 */
