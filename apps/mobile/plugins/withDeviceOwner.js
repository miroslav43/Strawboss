// BootReceiver.kt — restarts the keep-alive FGS + GPS tracking after a reboot or
// an OTA self-update, so a Device-Owner fleet phone recovers WITHOUT a human
// opening the app. The previous behaviour: a self-update killed the process and
// nothing brought it back to foreground, so background GPS/presence silently died
// after every update until someone tapped the app open (verified on a Galaxy S25).
// ---------------------------------------------------------------------------

const BOOT_RECEIVER_KT = `package ${PACKAGE}

import android.content.BroadcastReceiver
import android.content.Context
import android.content.Intent
import android.os.Build
import android.util.Log
import com.facebook.react.HeadlessJsTaskService

/**
 * GENERATED by plugins/withDeviceOwner.js — do not edit by hand.
 * Receives BOOT_COMPLETED (reboot) and MY_PACKAGE_REPLACED (OTA self-update) and
 * restarts the foreground services. The app is device owner + battery-opt
 * allow-listed, so starting a foreground service from the background is permitted.
 */
class BootReceiver : BroadcastReceiver() {
  override fun onReceive(context: Context, intent: Intent) {
    Log.i("StrawbossBoot", "BootReceiver fired: " + intent.action)
    try {
      // 1. Start the keep-alive FGS directly (native) so the app is at
      //    foreground-service importance immediately — this is what makes the
      //    subsequent JS-driven service starts allowed.
      val presence = Intent(context, PresenceService::class.java)
      if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
        context.startForegroundService(presence)
      } else {
        context.startService(presence)
      }
      // 2. Dispatch the JS boot-rearm task: post-OTA check-in, re-assert presence,
      //    and restart the Expo GPS foreground service when a machine is assigned.
      HeadlessJsTaskService.acquireWakeLockNow(context)
      context.startService(Intent(context, BootRearmService::class.java))
    } catch (t: Throwable) {
      Log.w("StrawbossBoot", "boot rearm dispatch failed", t)
    }
  }
}
`;

